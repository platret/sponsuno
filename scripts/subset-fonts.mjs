// Writes the self-hosted font files and their @font-face rules: `npm run fonts`. Run it after changing the character
// sets in scripts/font-glyphs.mjs, the faces below or the @fontsource packages, and commit the output. The build does
// not run it: it uses the committed files in src/assets/fonts/ and src/styles/fonts.css.
//
// Source: fontsource's "latin" woff2 files (devDependencies). Each face is cut into a core and an extra file with
// disjoint unicode-ranges (font-glyphs.mjs). Kept OpenType features: the ones browsers apply by default plus lnum and
// tnum (font-variant-numeric); dropped: fractions (frac/numr/dnom) and Manrope's pnum, which the site never asks for.
// Hinting stays (a few bytes; keeps Windows rendering as before). Glyph names stay too (post table format 2, about
// 0.4 KB per file): without them Chrome on macOS rasterises text below about 19 px slightly differently (measured
// pixel diffs against the fontsource files); with them every page renders pixel-identical.
import { readFile, writeFile, mkdir, copyFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import subsetFont from 'subset-font';
import { CORE_POINTS, EXTRA_POINTS, toRange } from './font-glyphs.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const outDir = path.join(root, 'src/assets/fonts');
const cssFile = path.join(root, 'src/styles/fonts.css');

/** Only the CD weights (DESIGN.md -> Typography). Do not add weights or families. */
const FACES = [
  { family: 'Cormorant Garamond', weight: 600, pkg: 'cormorant-garamond', name: 'cormorant-garamond-600' },
  { family: 'Manrope', weight: 400, pkg: 'manrope', name: 'manrope-400' },
  { family: 'Manrope', weight: 600, pkg: 'manrope', name: 'manrope-600' },
];
const FEATURES = ['kern', 'liga', 'calt', 'ccmp', 'locl', 'mark', 'mkmk', 'lnum', 'tnum'];
const PARTS = [
  { suffix: '', points: CORE_POINTS },
  { suffix: '-extra', points: EXTRA_POINTS },
];

await mkdir(outDir, { recursive: true });
const rules = [];
for (const face of FACES) {
  const source = path.join(root, 'node_modules/@fontsource', face.pkg, 'files', `${face.pkg}-latin-${face.weight}-normal.woff2`);
  const input = await readFile(source);
  for (const part of PARTS) {
    const text = String.fromCodePoint(...part.points);
    const output = await subsetFont(input, text, { targetFormat: 'woff2', keepFeatures: FEATURES, glyphNames: true });
    const file = `${face.name}${part.suffix}.woff2`;
    await writeFile(path.join(outDir, file), output);
    console.log(`src/assets/fonts/${file}: ${output.length} bytes (from ${input.length})`);
    rules.push(
      `@font-face {\n  font-family: '${face.family}';\n  font-style: normal;\n  font-display: swap;\n  font-weight: ${face.weight};\n`
        + `  src: url('../assets/fonts/${file}') format('woff2');\n  unicode-range: ${toRange(part.points)};\n}`,
    );
  }
}
// The fonts are licensed under the SIL Open Font License 1.1, which travels with modified copies
for (const pkg of new Set(FACES.map((f) => f.pkg))) {
  await copyFile(path.join(root, 'node_modules/@fontsource', pkg, 'LICENSE'), path.join(outDir, `${pkg}-OFL.txt`));
}

const header = `/* Generated by scripts/subset-fonts.mjs (npm run fonts): do not edit by hand.
   Self-hosted CD fonts (no request to Google), subset from @fontsource "latin". Each face has a core file (the text of
   the site, preloaded by every page's index.html) and an extra file (the rest of Latin-1 and General Punctuation),
   which the browser only fetches when such a character is on the page. The metric-matched fallbacks are in tokens.css. */`;
await writeFile(cssFile, `${header}\n${rules.join('\n')}\n`);
console.log(`Wrote src/styles/fonts.css (${rules.length} @font-face rules)`);
